/** ステージの物語を取り出す。無いステージは null。 */
export function storyFor(stageId) {
  const s = STORY[stageId];
  if (!s) return null;
  const ch = chapterFor(stageId);
  return { stageId, chapter: ch, title: s.title, lines: [...s.lines] };
}
