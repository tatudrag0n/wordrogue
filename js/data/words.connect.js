// ============================================================================
// ワードローグ — 接続詞
//
// 接続詞は「直前の語」に結合する。結合すると 1 つの合成語になる。
//   例 「律」+「スル」 -> 律スル
//
// 規則は 2 つ。
//
// 1. 同じ接続詞は 1 文に 1 回まで。
//      NG 「風ノ海ノ銃」 … ノが 2 回出ている。
//
// 2. 接続詞には優先順位があり、下位の接続詞は上位の接続詞より前に置けない。
//      NG 「雷ノ浸食サレタ剣」 … ノ (下位) が サレタ (上位) より先。
//      OK 「浸食サレタ雷ノ剣」 … サレタ (上位) が ノ (下位) より先。
//
// 結合元にない接続詞は宙に浮く (どの語とも結合せず、効果だけを少し得る)。
// 「無双」は接続詞を使えない語なので「思考セシ天下無双ノ剣」の ノは宙に浮く。
// ============================================================================

