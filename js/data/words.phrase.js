// Segmentation 辞書は「引ける語」だけなので、合成語はここには書かない。
// 連結した語列がこの表に一致したら「熟語成立」として追加効果が乗る。
//
// 2 文字の熟語 (火球・炎刃・毒弾…) は全部やめた。
//   文を自由に並べられるようになったので、2 語の連結だけで
//   本文と関係ない効果が乗って、名前と効果がずれる原因になっていた。
//
// 制約: 熟語は「語彙から引ける語だけで完全に分割できること」。
//   語は原則 1 文字（な形容詞の 2 語の語だけ例外）なので、熟語も 1 文字 3 語で組む。
//     吸血刃 = 吸 + 血 + 刃 / 感電弾 = 感 + 電 + 弾
//   2 字の熟語は作らない (作ると 1 語の連結と同じで 효과가意味と合わない)。
//   この規則は test/all.mjs の「熟語は実在の語だけで組める」で検査している。
//   熟語を足すときは必ずそのテストを通してから入れること。
// ============================================================================

