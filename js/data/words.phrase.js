// ============================================================================
// ワードローグ — 熟語ボーナス
//
// Segmentation 辞書は「引ける語」だけなので、合成語はここには書かない。
// 連結した語列がこの表に一致したら「熟語成立」として追加効果が乗る。
//
// 熟語は 2 段に分けてある。
//   三字熟語 (add)  … 1 文字 3 語。毒蝕弾 = 毒 + 蝕 + 弾。大きめの効果。
//   二字熟語 (add2) … 1 文字 2 語。発電 = 発 + 電。小さめの効果。
//
// 二字熟語は一度ぜんぶやめた (火球・炎刃・毒弾…)。2 語を並べるだけで
// 本文と関係ない効果が乗り、名前と効果がずれていたため。
// いまは次の条件で、選んだものだけ戻している。
//   - 実在する自然な二字熟語だけ。語を並べただけの造語は入れない。
//   - 形を表す語 (刃・弾・球・光・雷…) は使わない。末尾語と重なるのと、
//     「火球」のような形の熟語が名前と効果のずれの原因だったため。
//   - 効果は熟語の意味どおり (発電=感電、凍結=凍結、反射=反射…)。
//   - 三字熟語より小さい効果・小さい文力 (PHRASE_TIER)。
//
// 熟語自身の送り仮名 (pool):
//   動作を表す熟語 (サ変名詞) は「する」などの送り仮名を持てる。
//     発電 … する:adn*  → 発電する剣 (「電する」は単独では作れない)
//   書式は words.pool.js の形と同じ (送り仮名:役割[印])。
//   直前の語列がこの熟語になっているときだけ、その接続詞が付く。
//
// 熟語の検出は「文面中で最長の 1 つ」だけ (findCompound)。三字熟語の中に
// 二字熟語が含まれていても (大地震 ⊃ 地震) 三字熟語が勝つ。
// 1 つの文に熟語を 2 つ作っても、乗るのは最長の 1 つだけ。
//
// 制約: 熟語は「語彙から引ける語だけで完全に分割できること」。
//   この規則は test/all.mjs の「熟語は実在の語だけで組める」で検査している。
//   熟語を足すときは必ずそのテストを通してから入れること。
// ============================================================================

/** 熟語の格。文力 (power) と自然さ (natural) への加点。 */
export const PHRASE_TIER = {
  3: { power: 0.2, natural: 0.7 },
  2: { power: 0.1, natural: 0.4 },
};

const P = {};
const add = (phrase, name, desc, fx) => {
  P[phrase] = { phrase, name, desc, fx, tier: 3, pool: '', ...PHRASE_TIER[3] };
};
/** 二字熟語。pool は熟語自身の送り仮名 (例 'する:adn*')。 */
const add2 = (phrase, name, desc, fx, pool = '') => {
  P[phrase] = { phrase, name, desc, fx, tier: 2, pool, ...PHRASE_TIER[2] };
};

